/**
 * Issue #1624: the C4 component level of the context map, generated from the import graph instead
 * of drawn by hand: every file collapsed to its domain folder, one edge per pair of domains. The
 * output is sorted, so an unchanged tree gives the same text. `scripts/component-picture.ts` feeds
 * it dependency-cruiser's modules and writes the file (`bun run arch:picture`).
 */

/** The part of a dependency-cruiser module this reads. */
export type PictureModule = { source: string; dependencies: { resolved: string }[] };

/** The domain a source file belongs to, as `<app>/<folder>`; null for a file outside the three packages. */
export function domainOf(path: string): string | null {
  if (path.startsWith("packages/protocol/src/")) return "protocol";
  const found = /^apps\/(daemon|desktop)\/src\/(features\/)?([^/]+)/.exec(path);
  if (!found) return null;
  // a file at the root of src (main.ts) is its own node, named without the extension
  const folder = (found[3] as string).replace(/\.tsx?$/, "");
  return `${found[1]}/${folder}`;
}

const nodeId = (domain: string): string => domain.replaceAll(/[^\w]/g, "_");
const byText = (a: string, b: string): number => (a < b ? -1 : Number(a > b));

/** A domain imported by more than this many others is a base everyone leans on: listed, its edges not drawn. */
const BASE_IMPORTERS = 40;

/** The flowchart of one app: its domains as nodes and the imports between them as edges, sorted. */
function flowchart(app: string, domains: ReadonlySet<string>, edges: ReadonlySet<string>): string {
  const mine = [...domains].filter(
    (domain) => domain.startsWith(`${app}/`) || domain === "protocol",
  );
  const wanted = new Set(mine);
  const own = [...edges]
    .map((edge) => edge.split(" ") as [string, string])
    .filter(([from, to]) => from.startsWith(`${app}/`) && wanted.has(to));
  const importers = new Map<string, number>();
  for (const [, to] of own) importers.set(to, (importers.get(to) ?? 0) + 1);
  const bases = new Set(
    [...importers].filter(([, count]) => count > BASE_IMPORTERS).map(([to]) => to),
  );
  mine.sort(byText);
  const lines = mine.map(
    (domain) => `  ${nodeId(domain)}["${domain.slice(domain.indexOf("/") + 1)}"]`,
  );
  // One line per importing domain (`a --> b & c`, mermaid's own syntax): the file stays under the Markdown size limit.
  const drawn = new Map<string, string[]>();
  for (const [from, to] of own)
    if (!bases.has(to)) drawn.set(from, [...(drawn.get(from) ?? []), to]);
  for (const from of [...drawn.keys()].sort(byText))
    lines.push(
      `  ${nodeId(from)} --> ${(drawn.get(from) ?? []).sort(byText).map(nodeId).join(" & ")}`,
    );
  const note =
    bases.size === 0
      ? []
      : [
          "",
          `Imported by more than ${BASE_IMPORTERS} domains, so their edges are not drawn: ${[
            ...bases,
          ]
            .sort(byText)
            .map((to) => `\`${to.slice(to.indexOf("/") + 1)}\``)
            .join(", ")}.`,
        ];
  return ["```mermaid", "flowchart LR", ...lines, "```", ...note].join("\n");
}

/** The generated decision file: one mermaid flowchart per app, domains as nodes and imports as edges. */
export function componentPicture(modules: readonly PictureModule[]): string {
  const domains = new Set<string>();
  const edges = new Set<string>();
  for (const module of modules) {
    const from = domainOf(module.source);
    if (from === null) continue;
    domains.add(from);
    for (const dep of module.dependencies) {
      const to = domainOf(dep.resolved);
      if (to === null) continue;
      domains.add(to);
      if (to !== from) edges.add(`${from} ${to}`);
    }
  }
  return [
    "# Context map: the component picture, generated (issue #1624)",
    "",
    "The C4 component level of [the context map](2026-11-10-context-map.md), drawn from the import graph",
    "of the code: every file collapsed to its domain folder, an arrow where one domain imports another.",
    "Generated by `bun run arch:picture`; do not edit it by hand. Run the command again after a move",
    "and commit what it changes; an unchanged tree gives no diff.",
    "",
    "## Daemon",
    "",
    flowchart("daemon", domains, edges),
    "",
    "## Desktop",
    "",
    flowchart("desktop", domains, edges),
    "",
  ].join("\n");
}
